"""Regenerate the synthetic sample shipped with the static web demo.

Runs the real pipeline (``build_scene`` -> ``calibrate`` -> ``analyze``) with a
fixed seed and writes browser-ready assets into ``web/demo/assets/``:

* ``sample/analysis.json``  - unchanged ``shuttle-replay/analysis/v1`` output
* ``sample/synthetic_rally.mp4`` (H.264) and ``.webm`` (VP9) - the synthetic
  source video re-encoded frame by frame with the original PTS kept, because
  browsers cannot decode the pipeline's MPEG-4 Part 2 stream
* ``sample/provenance.json`` - how the files were made, plus SHA-256 digests
* ``court-data.js`` - court line centres from ``shuttle_replay.court``

Nothing here is real footage. Usage::

    uv run python web/build_sample.py            # rewrite the assets
    uv run python web/build_sample.py --check    # fail if analysis/court drifted
"""

import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path

import av

from shuttle_replay import __version__
from shuttle_replay.analysis import analyze
from shuttle_replay.calibration import calibrate
from shuttle_replay.court import COURT_LENGTH_M, COURT_WIDTH_M, NET_Y_M, court_lines
from shuttle_replay.synthetic import build_scene

WEB = Path(__file__).resolve().parent
ASSETS = WEB / "demo" / "assets"
SAMPLE = ASSETS / "sample"
SEED = 7


def run_pipeline(work):
    paths, _truth = build_scene(Path(work) / "inputs", seed=SEED)
    load = lambda p: json.loads(Path(p).read_text())  # noqa: E731
    cal = calibrate(load(paths["calibration_input"]))
    result = analyze(load(paths["tracks"]), load(paths["review"]), cal)
    return paths["video"], json.loads(json.dumps(result, default=_plain))


def _plain(o):
    if hasattr(o, "tolist"):
        return o.tolist()
    if hasattr(o, "item"):
        return o.item()
    raise TypeError(type(o).__name__)


def analysis_text(result):
    return json.dumps(result, indent=1, ensure_ascii=False, sort_keys=False) + "\n"


def court_module():
    data = {
        "source": "shuttle_replay.court (generated by web/build_sample.py)",
        "width_m": COURT_WIDTH_M,
        "length_m": COURT_LENGTH_M,
        "net_y_m": NET_Y_M,
        "lines": [[list(a), list(b)] for a, b in court_lines()],
    }
    return (
        "// SPDX-License-Identifier: AGPL-3.0-only\n"
        "// Generated by web/build_sample.py from src/shuttle_replay/court.py. Do not edit.\n"
        f"export const COURT = Object.freeze({json.dumps(data)});\n"
    )


def transcode(src, dst, codec, audio_codec):
    """Re-encode every decoded frame with its original PTS (VFR preserved)."""
    with av.open(str(src)) as inp, av.open(str(dst), "w") as out:
        vin = inp.streams.video[0]
        ain = inp.streams.audio[0]
        vs = out.add_stream(codec, rate=30)
        vs.width, vs.height, vs.pix_fmt = vin.width, vin.height, "yuv420p"
        vs.time_base = vin.time_base
        vs.codec_context.time_base = vin.time_base
        if codec == "libx264":
            vs.options = {"crf": "30", "preset": "medium", "bf": "0", "threads": "1"}
        else:
            vs.options = {"crf": "40", "b": "0", "deadline": "good", "threads": "1"}
        aus = out.add_stream(audio_codec, rate=ain.rate if audio_codec == "aac" else 48000)
        aus.layout = "mono"
        resampler = av.AudioResampler(
            format="fltp" if audio_codec == "aac" else "s16", layout="mono", rate=aus.rate
        )
        for frame in inp.decode(vin):
            frame.pict_type = av.video.frame.PictureType.NONE
            for pkt in vs.encode(frame):
                out.mux(pkt)
        for pkt in vs.encode():
            out.mux(pkt)
        inp.seek(0)
        for frame in inp.decode(inp.streams.audio[0]):
            for rf in resampler.resample(frame):
                for pkt in aus.encode(rf):
                    out.mux(pkt)
        for pkt in aus.encode():
            out.mux(pkt)


def video_pts(path):
    with av.open(str(path)) as c:
        s = c.streams.video[0]
        return [float(f.pts * s.time_base) for f in c.decode(s)]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify committed analysis/court only")
    args = ap.parse_args(argv)
    with tempfile.TemporaryDirectory() as work:
        video, result = run_pipeline(work)
        text = analysis_text(result)
        if args.check:
            ok = (SAMPLE / "analysis.json").read_text() == text
            ok &= (ASSETS / "court-data.js").read_text() == court_module()
            print("web sample up to date" if ok else "web sample drifted; rerun build_sample.py")
            return 0 if ok else 1
        SAMPLE.mkdir(parents=True, exist_ok=True)
        (SAMPLE / "analysis.json").write_text(text)
        (ASSETS / "court-data.js").write_text(court_module())
        outputs = {
            "synthetic_rally.mp4": ("libx264", "aac"),
            "synthetic_rally.webm": ("libvpx-vp9", "libopus"),
        }
        analysis_pts = [f["pts_s"] for f in result["frames"]]
        media = {}
        for name, (vc, ac) in outputs.items():
            transcode(video, SAMPLE / name, vc, ac)
            pts = video_pts(SAMPLE / name)
            drift = max(abs(a - b) for a, b in zip(pts, analysis_pts, strict=True))
            media[name] = {
                "video_codec": vc,
                "audio_codec": ac,
                "frames": len(pts),
                "max_pts_drift_vs_analysis_s": round(drift, 6),
                "sha256": sha256(SAMPLE / name),
            }
        provenance = {
            "synthetic": True,
            "real_footage": False,
            "generator": "web/build_sample.py",
            "package_version": __version__,
            "seed": SEED,
            "pipeline": [
                "shuttle_replay.synthetic.build_scene(seed=7)",
                "shuttle_replay.calibration.calibrate",
                "shuttle_replay.analysis.analyze",
            ],
            "source_video_note": "pipeline writes MPEG-4 Part 2; re-encoded frame by frame "
            "with original PTS for browser playback. Audio is a synthetic 440 Hz test tone.",
            "analysis_sha256": sha256(SAMPLE / "analysis.json"),
            "media": media,
        }
        (SAMPLE / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
        print(json.dumps(provenance, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
